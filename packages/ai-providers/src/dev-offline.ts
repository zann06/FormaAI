import type {
  CompletionRequest,
  CompletionResult,
  ConnectionTestResult,
  ProviderAdapter,
  ProviderConfig,
} from './types.js';

/**
 * Deterministic offline adapter used exclusively by the automated test suite and
 * by local development when `ENABLE_DEV_PROVIDER=true`.
 *
 * It is NOT a language model and never pretends to be one: it returns a
 * clearly-marked canned response derived from the prompt (so the pipeline can be
 * exercised end-to-end without network access). The UI labels it explicitly.
 */
export class DevOfflineAdapter implements ProviderAdapter {
  readonly type = 'dev-offline' as const;

  constructor(private readonly responder?: (request: CompletionRequest) => string) {}

  async complete(config: ProviderConfig, request: CompletionRequest): Promise<CompletionResult> {
    const started = Date.now();
    const text = this.responder ? this.responder(request) : defaultResponder(request);
    return {
      text,
      model: `dev-offline:${config.model}`,
      usage: { inputTokens: estimateTokens(request.messages), outputTokens: text.length },
      finishReason: 'stop',
      durationMs: Date.now() - started,
    };
  }

  async testConnection(config: ProviderConfig): Promise<ConnectionTestResult> {
    return {
      ok: true,
      message: 'Offline development provider is enabled. No external request was made.',
      model: config.model,
      latencyMs: 0,
    };
  }
}

function estimateTokens(messages: CompletionRequest['messages']): number {
  return messages.reduce((sum, m) => sum + Math.ceil(m.content.length / 4), 0);
}

function defaultResponder(request: CompletionRequest): string {
  if (request.jsonSchema) {
    const name = request.jsonSchema.name;
    if (name === 'section_draft') {
      return JSON.stringify({
        body:
          'This draft was produced by the offline development provider. Configure your own AI provider in Settings to generate real content.',
        citedChunkIds: [],
        warnings: ['Generated by the offline development provider — no AI model was used.'],
        placeholders: [],
      });
    }
    if (name === 'evidence_mapping') {
      return JSON.stringify({ sections: [] });
    }
    return JSON.stringify({});
  }
  return 'OK';
}
